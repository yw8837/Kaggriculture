"""Build a non-self-referential manifest for this public-meta evidence bundle."""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "source_manifest.json"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def main() -> None:
    entries = []
    for path in sorted(ROOT.rglob("*")):
        relative = path.relative_to(ROOT)
        if (
            not path.is_file()
            or path == OUTPUT
            or "raw" in relative.parts
            or "__pycache__" in relative.parts
        ):
            continue
        entries.append(
            {
                "path": relative.as_posix(),
                "bytes": path.stat().st_size,
                "sha256": _sha(path),
            }
        )
    payload = {
        "schema_version": 1,
        "created_at_utc": datetime.now(UTC).isoformat().replace("+00:00", "Z"),
        "exclusions": {
            "source_manifest.json": "self-reference",
            "raw/": "89 downloaded files are individually bound by kernel_output_manifest.jsonl and rehashed by verify_public_meta.py",
            "model_v8 raw download": "The four official v8 files live under ignored dist/model-v8-download; exact sizes/hashes and the retrieval command are tracked in model_v8/file_inventory_v8.json.",
            "__pycache__/": "generated bytecode",
        },
        "entries": entries,
    }
    if OUTPUT.is_file():
        existing = json.loads(OUTPUT.read_text(encoding="utf-8"))
        candidate = dict(payload)
        candidate["created_at_utc"] = existing.get("created_at_utc")
        if candidate == existing:
            payload = existing
    output_text = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != output_text:
        OUTPUT.write_text(output_text, encoding="utf-8", newline="\n")
    print(json.dumps({"entries": len(entries), "output": str(OUTPUT)}, sort_keys=True))


if __name__ == "__main__":
    main()
